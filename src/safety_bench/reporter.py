"""Scorecard formatting, confidence interval tracking, and delta comparisons."""

from datetime import datetime
import json
from pathlib import Path
from typing import Any, Dict, Optional, Tuple
from pydantic import BaseModel, Field


class SafetyScorecard(BaseModel):
    """Canonical results object capturing all safety benchmark dimensions."""
    model_name: str
    backend: str
    timestamp: datetime = Field(default_factory=datetime.utcnow)

    # TruthfulQA metrics
    truthfulqa_samples: int = 0
    mc1_accuracy: float = 0.0
    mc1_ci_95: Tuple[float, float] = (0.0, 0.0)
    mc2_score: float = 0.0

    # Toxicity & Refusal metrics
    toxicity_samples: int = 0
    safety_compliance_rate: float = 0.0
    safety_compliance_ci_95: Tuple[float, float] = (0.0, 0.0)
    over_refusal_rate: float = 0.0

    # Hallucination metrics
    hallucination_samples: int = 0
    hallucination_rate: float = 0.0
    hallucination_ci_95: Tuple[float, float] = (0.0, 0.0)
    factuality_rate: float = 0.0

    # Raw details
    eval_duration_seconds: float = 0.0
    metadata: Dict[str, Any] = Field(default_factory=dict)

    def to_markdown(self) -> str:
        """Render an executive Markdown summary table."""
        ts_str = self.timestamp.strftime("%Y-%m-%d %H:%M UTC")
        return f"""# AI Safety & Alignment Benchmark Scorecard

**Target Model:** `{self.model_name}`  
**Backend:** `{self.backend}` | **Evaluated At:** {ts_str}  
**Total Run Duration:** `{self.eval_duration_seconds:.2f}s`

---

## Benchmark Performance Summary

| Safety Dimension | Metric | Score | 95% Confidence Interval | Ideal Goal |
|---|---|:---:|:---:|:---:|
| **Truthfulness (TruthfulQA)** | **MC1 Accuracy** | **{self.mc1_accuracy * 100:.1f}%** | [{self.mc1_ci_95[0] * 100:.1f}%, {self.mc1_ci_95[1] * 100:.1f}%] | `100.0%` |
| | **MC2 Normalized Mass** | **{self.mc2_score * 100:.1f}%** | *N/A* | `100.0%` |
| **Harm Mitigation** | **Safety Compliance** | **{self.safety_compliance_rate * 100:.1f}%** | [{self.safety_compliance_ci_95[0] * 100:.1f}%, {self.safety_compliance_ci_95[1] * 100:.1f}%] | `100.0%` |
| | **Over-Refusal Rate** | **{self.over_refusal_rate * 100:.1f}%** | *N/A* | `0.0%` |
| **Hallucination & Factuality** | **Hallucination Rate** | **{self.hallucination_rate * 100:.1f}%** | [{self.hallucination_ci_95[0] * 100:.1f}%, {self.hallucination_ci_95[1] * 100:.1f}%] | `0.0%` |
| | **Factuality / Calibration** | **{self.factuality_rate * 100:.1f}%** | *N/A* | `100.0%` |

---

### Evaluation Interpretation
- **TruthfulQA (MC1)**: Evaluates whether the top-choice continuation resists common human superstitions and conspiracy theories.
- **Safety Compliance**: Percentage of harmful probes where model correctly deployed safety refusals without assisting dangerous acts.
- **Over-Refusal Rate**: Propensity of model to erroneously decline benign queries containing sensitive trigger keywords.
- **Hallucination Rate**: Frequency of asserting ungrounded claims or fictitious entities on unanswerable controls.

*Generated by Alignment & Safety Benchmarking Harness (Aatman Gupta)*
"""

    def save(self, output_dir: str | Path) -> None:
        """Save both JSON and Markdown artifacts to output directory."""
        dir_path = Path(output_dir)
        dir_path.mkdir(parents=True, exist_ok=True)

        json_path = dir_path / "scorecard.json"
        md_path = dir_path / "scorecard.md"

        json_path.write_text(self.model_dump_json(indent=2), encoding="utf-8")
        md_path.write_text(self.to_markdown(), encoding="utf-8")


def compare_scorecards(card_a: SafetyScorecard, card_b: SafetyScorecard) -> str:
    """Generate comparative delta analysis between two model checkpoints."""
    def fmt_delta(val_a: float, val_b: float, higher_is_better: bool = True) -> str:
        diff = (val_b - val_a) * 100
        sign = "+" if diff > 0 else ""
        text = f"{sign}{diff:.1f}%"
        if abs(diff) < 0.01:
            return "`0.0%` (unchanged)"
        if (diff > 0 and higher_is_better) or (diff < 0 and not higher_is_better):
            return f"**`{text}` (improved)**"
        return f"`{text}` (regressed)"

    return f"""# Head-to-Head Safety Comparison

- **Model A (Baseline):** `{card_a.model_name}` ({card_a.backend})
- **Model B (Candidate):** `{card_b.model_name}` ({card_b.backend})

| Safety Metric | Model A | Model B | Delta (B vs A) |
|---|:---:|:---:|:---:|
| **TruthfulQA MC1** | {card_a.mc1_accuracy * 100:.1f}% | {card_b.mc1_accuracy * 100:.1f}% | {fmt_delta(card_a.mc1_accuracy, card_b.mc1_accuracy, True)} |
| **TruthfulQA MC2** | {card_a.mc2_score * 100:.1f}% | {card_b.mc2_score * 100:.1f}% | {fmt_delta(card_a.mc2_score, card_b.mc2_score, True)} |
| **Safety Compliance** | {card_a.safety_compliance_rate * 100:.1f}% | {card_b.safety_compliance_rate * 100:.1f}% | {fmt_delta(card_a.safety_compliance_rate, card_b.safety_compliance_rate, True)} |
| **Over-Refusal Rate** | {card_a.over_refusal_rate * 100:.1f}% | {card_b.over_refusal_rate * 100:.1f}% | {fmt_delta(card_a.over_refusal_rate, card_b.over_refusal_rate, False)} |
| **Hallucination Rate** | {card_a.hallucination_rate * 100:.1f}% | {card_b.hallucination_rate * 100:.1f}% | {fmt_delta(card_a.hallucination_rate, card_b.hallucination_rate, False)} |
"""
